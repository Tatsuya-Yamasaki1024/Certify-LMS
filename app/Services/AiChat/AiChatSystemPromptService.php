<?php

declare(strict_types=1);

namespace App\Services\AiChat;

/**
 * AI チャットのシステムプロンプトを構築するサービス。
 */
final class AiChatSystemPromptService
{
    /**
     * コンテキストに応じたシステムプロンプトを構築する。
     */
    public function build(string $context): string
    {
        return implode("\n\n", [
            'あなたは CertifyLMS の受講生を支援する学習アシスタントです。',
            '受講生の質問を理解し、学習内容の理解や問題解決を支援してください。',
            '説明は日本語を基本とし、必要に応じて具体例や手順を示してください。',
            '確実でない情報は断定せず、不明な点は不明であると伝えてください。',
            '試験の合格や資格取得を保証する表現は避けてください。',
            '現在の受講資格や教材の情報は参考コンテキストです。質問に関係する場合にのみ利用してください。',
            'コンテキストに教材本文は含まれていません。教材本文を確認したかのように振る舞わず、必要なら受講生に該当箇所の提示を依頼してください。',
            ...($context !== ''
                ? ["以下は現在の会話に関するコンテキストです。\n{$context}"]
                : []),
        ]);
    }
}
